# Programa que mostra a média entre as 4 notas do aluno

num1 = int(input('Digite a sua 1° nota: '))
num2 = int(input('Digite a sua 2° nota: '))
num3 = int(input('Digite a sua 3° nota: '))
num4 = int(input('Digite a sua 4° nota: '))

media = (num1 + num2 + num3 + num4 / 4)

print(f'A sua média final é = {media}')

